"""One command from a song file to a playable LED level (GD3-220): measures BPM and offset, checks the song suits the
game (bars with a standout hit, hit_grid.py) and whether it sits on its beat grid, builds the LED data, picks a
difficulty from the density of tap-worthy hits and a palette set, writes tools/charting/levels/<id>.py (rerunnable,
editable) and the chart, then checks it (tap salience, autoplay through the level, timing tolerance) and prints a report.
Stops and asks only when unsure: two close BPM candidates (pass --bpm) or a song that fails the fitness check (--force).
Usage: python tools/charting/auto_level.py <song.mp3> [--id ID] [--title T] [--artist A] [--bpm B] [--offset S]
       [--difficulty 1-5] [--force] [--no-godot]
Related: tools/charting/song_tempo.py, tools/charting/led_level.py, tools/charting/check_chart.gd, docs/chart_format.md
"""
import argparse
import os
import random
import re
import shutil
import statistics
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "audio"))
import build_spectrum  # noqa: E402
import led_level  # noqa: E402
from hit_grid import standout_share  # noqa: E402
from hit_level import ROOT, hit_table  # noqa: E402
from loudness_onsets import SAMPLE_RATE, decode  # noqa: E402
from song_tempo import estimate  # noqa: E402
from tap_salience import GOOD_ATTACK, GOOD_STANDOUT, chart_salience, envelope  # noqa: E402

GODOT = os.environ.get("GODOT", "D:/Godot_v4.6.1-stable_win64.exe/Godot_v4.6.1-stable_win64_console.exe")
# Fitness: share of bars holding a standout hit ("X" in hit_grid.py); the kept songs measured 60-79 %.
MIN_STANDOUT_BARS = 0.5
# On the grid: share of LED jumps within GRID_REACH beats of a quarter beat (chance alone gives 40 %; songs fitted on
# their hits measured 75-89 %), then taps snap to quarter beats.
GRID_REACH = 0.05
MIN_ON_GRID = 0.6
# Difficulty from tap-worthy hits (either salience measure passes) per bar: below each bound -> that difficulty.
# Measured 2026-10-15: tribal/neon ~0.8-1.0, temple ~1.3, fault_line/pulse_drive ~2.2, the_dawn_assembly 3.4.
DIFFICULTY_BOUNDS = ((1.0, 2), (2.0, 3))
DENSE_DIFFICULTY = 4
# Phase palettes: four drawn from POOL (at most one with a warm sky), the finale always VOID.
POOL = ["indigo", "ocean", "aurora", "glacier", "ultraviolet", "sunset", "ember"]
WARM = {"sunset", "ember"}
FINALE = "void"
UNDER_EVERY = 24
LEVEL_SCRIPT = '''"""{title}: LED level generated by tools/charting/auto_level.py ({date_note}). Edit SONG and rerun to rebuild.
Usage: python tools/charting/levels/{id}.py   Related: tools/charting/led_level.py
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from led_level import build  # noqa: E402

SONG = {song}

if __name__ == "__main__":
    build(SONG)
'''


def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def pick_palettes(song_id):
    generator = random.Random(song_id)
    palettes = []
    for name in generator.sample(POOL, len(POOL)):
        if name in WARM and any(p in WARM for p in palettes):
            continue
        palettes.append(name)
        if len(palettes) == 4:
            break
    return palettes + [FINALE]


def pick_difficulty(samples, bpm):
    table, _ = hit_table(samples, bpm)
    minutes = len(samples) / SAMPLE_RATE / 60.0
    per_bar = sum(1 for _, _, standout, attack in table if standout >= GOOD_STANDOUT or attack >= GOOD_ATTACK) \
        / max(minutes * bpm / 4.0, 1e-6)
    for bound, difficulty in DIFFICULTY_BOUNDS:
        if per_bar < bound:
            return difficulty, per_bar
    return DENSE_DIFFICULTY, per_bar


def on_grid_share(jumps, bpm, offset):
    beats = [(time_sec - offset) * bpm / 60.0 for time_sec, _ in jumps]
    return sum(1 for b in beats if abs(b * 4.0 - round(b * 4.0)) / 4.0 <= GRID_REACH) / max(len(beats), 1)


def run_godot(arguments):
    result = subprocess.run([GODOT, "--headless", "--path", ROOT] + arguments, capture_output=True, text=True,
                            encoding="utf-8", errors="replace")
    return result.returncode, result.stdout + result.stderr


def godot_checks(song_id, report):
    code, output = run_godot(["--import"])
    if code != 0:
        report.append("godot import: FAILED (exit %d)" % code)
        return False
    chart = "--chart=res://assets/music/%s.chart.json" % song_id
    code, output = run_godot(["-s", "res://tools/charting/check_chart.gd", "--", chart])
    line = next((l for l in output.splitlines() if l.startswith("CHECK")), "CHECK fail no output")
    report.append("autoplay: %s" % line[6:])
    passed = code == 0 and line.startswith("CHECK ok")
    code, output = run_godot(["-s", "res://tools/charting/tolerance_report.gd", "--", chart])
    line = next((l for l in output.splitlines() if l.startswith("TOLERANCE")), "TOLERANCE missing")
    report.append("tolerance: %s" % line[10:])
    return passed


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("song")
    parser.add_argument("--id")
    parser.add_argument("--title")
    parser.add_argument("--artist", default="Unknown")
    parser.add_argument("--bpm", type=float)
    parser.add_argument("--offset", type=float)
    parser.add_argument("--difficulty", type=int, choices=range(1, 6))
    parser.add_argument("--force", action="store_true", help="build even when the song fails the fitness check")
    parser.add_argument("--no-godot", action="store_true", help="skip the autoplay and tolerance checks")
    args = parser.parse_args()
    os.chdir(ROOT)
    source = os.path.abspath(args.song)
    if not os.path.isfile(source) or not source.lower().endswith(".mp3"):
        sys.exit("auto_level: %s is not an .mp3 file" % args.song)
    song_id = args.id or slug(os.path.splitext(os.path.basename(source))[0])
    audio = os.path.join(ROOT, "assets", "music", song_id + ".mp3")
    if os.path.normcase(source) != os.path.normcase(audio):
        if os.path.exists(audio):
            sys.exit("auto_level: %s already exists; pass --id or use that file" % os.path.relpath(audio, ROOT))
        shutil.copyfile(source, audio)
        print("copied to %s" % os.path.relpath(audio, ROOT))

    print("[1/6] tempo")
    tempo = estimate(audio, args.bpm)
    candidates = ", ".join("%.1f (%.2f)" % c for c in tempo["candidates"])
    if tempo["ambiguous"]:
        print("UNSURE: two close BPM candidates: %s\n  listen and rerun with --bpm <one of them>" % candidates)
        sys.exit(2)
    bpm = tempo["bpm"]
    offset = args.offset if args.offset is not None else tempo["offset"]
    samples = decode(audio)

    print("[2/6] fitness")
    share = standout_share(envelope(samples), bpm, offset)
    if share < MIN_STANDOUT_BARS and not args.force:
        print("UNFIT: only %.0f%% of bars hold a standout hit (need %.0f%%). Taps would not match what players hear.\n"
              "  check: python tools/charting/hit_grid.py %s %.2f %.4f   (or rerun with --force)"
              % (100 * share, 100 * MIN_STANDOUT_BARS, os.path.relpath(audio, ROOT), bpm, offset))
        sys.exit(3)

    print("[3/6] LED data and grid")
    build_spectrum.build(song_id)
    jumps = led_level.led_jumps(samples)
    on_grid = on_grid_share(jumps, bpm, offset)
    difficulty, density = pick_difficulty(samples, bpm)
    difficulty = args.difficulty or difficulty

    print("[4/6] level")
    song = {"id": song_id, "audio": song_id, "title": args.title or song_id.replace("_", " ").title(), "artist": args.artist,
            "bpm": bpm, "offset": offset, "difficulty": difficulty, "under_every": UNDER_EVERY,
            "palettes": pick_palettes(song_id)}
    if on_grid >= MIN_ON_GRID:
        song["grid"] = 0.25
    script = os.path.join(ROOT, "tools", "charting", "levels", song_id + ".py")
    with open(script, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(LEVEL_SCRIPT.format(title=song["title"], id=song_id, song=repr(song),
                                         date_note="BPM/offset measured, difficulty from hit density"))
    summary = led_level.build(song, jumps)

    print("[5/6] tap salience")
    standout, attack = chart_salience(os.path.join(ROOT, "assets", "music", song_id + ".chart.json"))
    salience_ok = bool(standout) and statistics.median(standout) >= GOOD_STANDOUT \
        and statistics.median(attack) >= GOOD_ATTACK
    report = ["song: %s  %.2f BPM  offset %.4f s  (candidates %s)" % (song_id, bpm, offset, candidates),
              "fitness: %.0f%% of bars hold a standout hit" % (100 * share),
              "grid: %.0f%% of LED jumps on quarter beats -> %s" % (100 * on_grid, "snapped" if "grid" in song else "free"),
              "difficulty: %d (%.1f tap-worthy hits per bar)  palettes %s" % (difficulty, density, song["palettes"]),
              "level: %d taps, %d bursts, end beat %d, %d builder warnings" % (summary["taps"], summary["bursts"],
                                                                               summary["end_beat"], summary["warnings"]),
              "salience: standout x%.2f attack x%.2f -> %s" % (statistics.median(standout) if standout else 0.0,
                                                              statistics.median(attack) if attack else 0.0,
                                                              "OK" if salience_ok else "WEAK")]
    passed = True
    if not args.no_godot:
        print("[6/6] autoplay and tolerance (Godot)")
        passed = godot_checks(song_id, report)
    print("\nREPORT\n  " + "\n  ".join(report))
    print("files: assets/music/%s.chart.json, assets/music/%s.spectrum.json, tools/charting/levels/%s.py"
          % (song_id, song_id, song_id))
    if not passed:
        sys.exit(1)


if __name__ == "__main__":
    main()
